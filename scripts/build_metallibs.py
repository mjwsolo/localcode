"""Compile the Metal kernels of the bundled llama-server ahead of time.

llama-server embeds its Metal sources and compiles them when it starts, which
takes 20-30 s whenever macOS's shader cache is cold. This builds the same
sources into ggml-metal-<key>.bundle files that the server loads instead
(see ggml_metal_library_init). <key> hashes the embedded sources plus the
compile macros the server would use, so a file built from other sources or for
other hardware is ignored and the server falls back to compiling.

Needs Xcode's `metal` compiler (CI macOS runners have it).

    python scripts/build_metallibs.py <cmake build dir> <out dir>
    python scripts/build_metallibs.py --check <cmake build dir> src/localcode/bin

--check compiles nothing: it fails unless <dir> holds exactly the files the
current sources need, so a shipped library can never silently go stale.
"""
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEVICE_M = ROOT / "llama-cpp-turboquant/ggml/src/ggml-metal/ggml-metal-device.m"

# The two macro sets the server builds at runtime on Apple Silicon. Every Apple
# GPU reports bfloat support; Metal 4 (tensor API) devices compile with
# language 4.0 and the full turbo3 LUT, the rest with the 4-magnitude LUT.
VARIANTS = {
    "tensor": {"lang": 4, "std": "metal4.0", "min": "26.0",
               "macros": {"GGML_METAL_EMBED_LIBRARY": "1", "GGML_METAL_HAS_BF16": "1", "GGML_METAL_HAS_TENSOR": "1", "TURBO_SPARSE_V": "1"}},
    "base":   {"lang": 0, "std": "metal3.1", "min": "14.0",
               "macros": {"GGML_METAL_EMBED_LIBRARY": "1", "GGML_METAL_HAS_BF16": "1", "TURBO_USE_4MAG": "1", "TURBO_SPARSE_V": "1"}},
}
FNV_OFFSET, FNV_PRIME, MASK = 1469598103934665603, 1099511628211, (1 << 64) - 1


def fnv(data: bytes, h: int = FNV_OFFSET) -> int:
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & MASK
    return h


def kinds() -> list[str]:
    block = DEVICE_M.read_text().split("#define GGML_METAL_LIBS", 1)[1].split("\n\n", 1)[0]
    return re.findall(r"X\(\s*\w+\s*,\s*(\w+)\s*\)", block)


def key(sources: list[bytes], v: dict) -> int:
    h_src = 0
    for s in sources:
        h_src ^= fnv(s)
    desc = f"lang={v['lang']}" + "".join(f";{k}={v['macros'][k]}" for k in sorted(v["macros"]))
    return fnv(desc.encode(), h_src)


def main(build: Path, out: Path, check: bool = False) -> int:
    gen = build / "ggml/src/ggml-metal/autogenerated"
    files = [gen / f"ggml-metal-embed-{k}.metal" for k in kinds()]
    missing = [f.name for f in files if not f.is_file()]
    if missing:
        sys.exit(f"embedded sources not generated: {missing[:3]} (build the ggml-metal target first)")
    sources = [f.read_bytes() for f in files]
    if check:
        want = {f"ggml-metal-{key(sources, v):016x}.bundle" for v in VARIANTS.values()}
        have = {p.name for p in out.glob("ggml-metal-*.bundle")}
        if want != have:
            sys.exit(f"shipped Metal libraries do not match the sources: need {sorted(want)}, have {sorted(have)}. "
                     "Download the 'metallibs' artifact of the TurboQuant workflow into src/localcode/bin.")
        print("shipped Metal libraries match the sources")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for name, v in VARIANTS.items():
        k = key(sources, v)
        target = out / f"ggml-metal-{k:016x}.bundle"
        # One library per kind, like the runtime compile: the kinds share helper
        # symbols, so they cannot be linked into a single metallib.
        blob = bytearray(b"LCMETAL1") + struct.pack("<I", len(files))
        with tempfile.TemporaryDirectory() as tmp:
            for kind, f in zip(kinds(), files):
                air, lib = Path(tmp) / f"{kind}.air", Path(tmp) / f"{kind}.metallib"
                cmd = ["xcrun", "-sdk", "macosx", "metal", "-c", str(f), "-o", str(air),
                       f"-std={v['std']}", f"-mmacosx-version-min={v['min']}"]
                cmd += [f"-D{m}={val}" for m, val in v["macros"].items()]
                subprocess.run(cmd, check=True)
                subprocess.run(["xcrun", "-sdk", "macosx", "metallib", str(air), "-o", str(lib)], check=True)
                data, encoded = lib.read_bytes(), kind.encode()
                blob += struct.pack("<I", len(encoded)) + encoded + struct.pack("<Q", len(data)) + data
        target.write_bytes(bytes(blob))
        print(f"{name}: {target.name} ({target.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    check = args[:1] == ["--check"]
    if check:
        args = args[1:]
    raise SystemExit(main(Path(args[0]), Path(args[1]), check))
